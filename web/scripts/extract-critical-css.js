const fs = require('fs');
const path = require('path');

/**
 * Extract critical CSS that should be inlined
 * This includes CSS custom properties and base styles
 */
function extractCriticalCSS() {
  const globalsPath = path.join(__dirname, '../app/globals.css');
  const globals = fs.readFileSync(globalsPath, 'utf8');

  // Extract only :root variables and @theme inline
  const criticalCSS = [];

  // Extract :root block
  const rootMatch = globals.match(/:root\s*\{[^}]+\}/s);
  if (rootMatch) {
    criticalCSS.push(rootMatch[0]);
  }

  // Extract .dark block
  const darkMatch = globals.match(/\.dark\s*\{[^}]+\}/s);
  if (darkMatch) {
    criticalCSS.push(darkMatch[0]);
  }

  // Extract @theme inline block
  const themeMatch = globals.match(/@theme inline\s*\{[^}]+\}/s);
  if (themeMatch) {
    criticalCSS.push(themeMatch[0]);
  }

  // Extract base layer for critical elements
  const baseStyles = `
* {
  border-color: var(--color-border);
  outline-color: color-mix(in oklch, var(--color-ring), transparent 50%);
}
body {
  background-color: var(--color-background);
  color: var(--color-foreground);
  margin: 0;
  padding: 0;
}
`;

  criticalCSS.push(baseStyles);

  const output = criticalCSS.join('\n\n');

  // Save to file
  const cssOutputPath = path.join(__dirname, '../app/critical.css');
  fs.writeFileSync(cssOutputPath, output);

  // Also create TypeScript module for edge runtime compatibility
  // Escape backticks and ${} in the CSS content
  const escapedCSS = output
    .replace(/\\/g, '\\\\')  // Escape backslashes
    .replace(/`/g, '\\`')     // Escape backticks
    .replace(/\$\{/g, '\\${'); // Escape template literals

  const tsContent = `// Auto-generated critical CSS - DO NOT EDIT
// Generated by scripts/extract-critical-css.js during prebuild

export const criticalCSS = \`${escapedCSS}\`;
`;
  const tsOutputPath = path.join(__dirname, '../app/critical-css.ts');
  fs.writeFileSync(tsOutputPath, tsContent);

  console.log('✓ Critical CSS extracted to app/critical.css');
  console.log('✓ Created app/critical-css.ts for edge runtime');
  console.log(`  Size: ${Buffer.byteLength(output, 'utf8')} bytes`);

  return output;
}

if (require.main === module) {
  extractCriticalCSS();
}

module.exports = { extractCriticalCSS };
